/// grad(), jvp() and vjp() -- reverse- and forward-mode automatic
/// differentiation as AST-level source transforms (pre-typecheck), surfaced
/// through the `ad` module. The header below documents grad; jvp's surface,
/// ABI, and subset are documented at `synthesizeJvp` (its subset is a strict
/// superset -- forward mode needs no reverse sweep, so the discipline
/// checks below do not apply to it), vjp's -- the SEEDED reverse mode for an
/// ARRAY-valued function, `f__vjp(args..., __seed, buffers...)` accumulating
/// J^T seed -- at `synthesizeRev`, and the composition driver
/// (`ad.jvp(ad.grad(f))` = HVP) at `expandModule`. jvp accepts array-valued
/// returns too (`(y, J v)`), so the pair is a matrix-free linearization:
/// forward action and adjoint action from one resolved function, no
/// Jacobian formed (plan-fortran-killer-2 section 6.3).
///
/// Surface form: `import ad as ad` then `ad.grad(f)` where `f` is a
/// top-level function in the same module returning a Float scalar. The pass
/// is import-gated (no `import ad` -> no-op; bare `grad(...)` is unbound,
/// same module rule as the ml/ppl surfaces). The expression rewrites to a
/// reference to a synthesized function `f__grad`, so
/// `ad.grad(f)(args..., buffers...)` and `let g = ad.grad(f)` both work:
///
///   function f__grad(p1, ..., pn,                    // originals
///                    __g_pA: mut <type of pA>, ...)   // one out-buffer per
///                                                      // Float-ARRAY param
///       -> Float                                      // the primal value
///       |  (Float, Float, ...)                        // + one gradient per
///                                                      //   Float SCALAR param
///
/// Gradient out-buffers are ACCUMULATED into (callers zero them; repeated
/// calls sum, PyTorch .grad semantics). Int / int-array params (edge lists,
/// sizes) are non-differentiable and get no buffer.
///
/// Why source-to-source, pre-typecheck: the generated derivative is itself
/// type-checked, lowered, and code-generated by the existing pipeline,
/// including the symmetry system, so adjoints of symmetric computations
/// inherit triangular storage with no AD-specific storage logic.
///
/// THE AD-ABLE SUBSET. Differentiated function bodies may contain:
///   - `let x = e` / `let mut x = e` (single-name patterns)
///   - accumulation `x += e`, `x -= e`, `a(i...) += e`, `a(i...) -= e`
///     (and their spelled-out forms `x = x + e` etc.)
///   - general (re)assignment in STRAIGHT-LINE positions; inside loops only
///     the additive-self pattern is allowed on scalars (loop-carried
///     recurrences would need taping/reversal)
///   - element writes `a(i...) = e` (construction of fresh arrays)
///   - `for k in lo..hi { ... }` to any nesting depth (int bounds,
///     non-differentiable); the ADJOINT loop runs in the SAME direction,
///     exact for the accumulation subset
///   - scalar arithmetic + - * / (and `^` by an int literal), unary minus
///   - math intrinsics (exp/log/sqrt/trig/hyperbolic; floor/ceil have zero
///     derivative). lgamma differentiates to digamma, which makes the
///     gamma/beta/poisson log-likelihoods AD-able. NOT digamma itself: its
///     derivative is trigamma, which the language does not have, so it is
///     REFUSED rather than silently differentiated to zero
///     (zeroDerivIntrinsics vs derivRule's None, below)
///   - array reads `a(i...)` at integer index expressions
///   - calls to other AD-able functions in the same module, INLINED
///     (recursion rejected by a depth cap)
///   - float array literals
///
/// Deliberately rejected (clean errors): if/match in differentiated code,
/// combinator computations AND combinator operators, tuple-pattern lets,
/// reads of an accumulator from expressions inside the loop that mutates it,
/// writes to an accumulator after straight-line code has read it,
/// array-alias lets, callees with mut params, unit-carrying and complex
/// parameters/returns (a gradient's units are <loss>/<param>, which this ABI
/// cannot express; complex needs a Wirtinger convention), calls to names
/// with no derivative rule (`abs`, `min`, imports -- silence would drop
/// their term), and user bindings spelled like the synthesized names
/// (`__g_*`, `__t_*`, `__primal` -- shadowing corrupts the sweep).
///
/// Loop-body `let`s are recomputed inside the adjoint loop (recompute-based
/// tape); function-level `let`s stay in scope across the reverse sweep, so
/// nothing else is stored. The C(n+r-1, r) triangular-tape result falls out
/// of storing intermediates in whatever (possibly symmetric) arrays the
/// forward pass already uses.
